const state = {
  language: "en",
  wordIndex: 0,
};

const copyNodes = document.querySelectorAll("[data-copy]");
const languageButton = document.querySelector("[data-language-button]");
const changingWord = document.querySelector("[data-changing-word]");
const installDialog = document.querySelector("[data-install-dialog]");

function applyLanguage(language) {
  state.language = language;
  state.wordIndex = 0;
  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  copyNodes.forEach((node) => {
    const key = node.dataset.copy;
    if (copy[language][key]) {
      node.textContent = copy[language][key];
    }
  });
  changingWord.textContent = copy[language].changingWords[0];
  languageButton.textContent = language === "en" ? "中文" : "EN";
  localStorage.setItem("browseMemoryWebsiteLanguage", language);
}

function rotateWord() {
  changingWord.classList.add("is-changing");
  window.setTimeout(() => {
    const words = copy[state.language].changingWords;
    state.wordIndex = (state.wordIndex + 1) % words.length;
    changingWord.textContent = words[state.wordIndex];
    changingWord.classList.remove("is-changing");
  }, 180);
}

const revealObserver = new IntersectionObserver(
  (entries, observer) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.12 },
);

document.querySelectorAll(".reveal").forEach((node) => revealObserver.observe(node));

languageButton.addEventListener("click", () => {
  applyLanguage(state.language === "en" ? "zh" : "en");
});

document.querySelectorAll("[data-open-install]").forEach((button) => {
  button.addEventListener("click", () => {
    installDialog.showModal();
    document.body.classList.add("dialog-open");
  });
});

document.querySelector("[data-close-install]").addEventListener("click", () => {
  installDialog.close();
});

installDialog.addEventListener("close", () => {
  document.body.classList.remove("dialog-open");
});

installDialog.addEventListener("click", (event) => {
  const bounds = installDialog.getBoundingClientRect();
  const outside =
    event.clientX < bounds.left ||
    event.clientX > bounds.right ||
    event.clientY < bounds.top ||
    event.clientY > bounds.bottom;
  if (outside) {
    installDialog.close();
  }
});

const preferredLanguage =
  localStorage.getItem("browseMemoryWebsiteLanguage") ||
  (navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en");

applyLanguage(preferredLanguage);

if (!window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
  window.setInterval(rotateWord, 2600);
}
